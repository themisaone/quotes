#!/usr/bin/env node
/* eslint-disable */
/**
 * One-shot script to split the (already responsive-split) base
 * `public/style.css` into feature-themed files.  Each output gets a fresh
 * banner; the load order in `index.html` mirrors the original line order so
 * cascade behaviour is preserved.
 *
 * If a section is non-contiguous in the original (e.g. "search" rules at
 * 405-899 and 1709-1811), both ranges go in the SAME output file in their
 * original order — selectors in those gaps were checked manually to ensure
 * no cross-section overrides exist (see PR description).
 *
 * Re-run with:  node scripts/split-base-css.js
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC  = path.join(ROOT, 'public', 'style.css');

const raw = fs.readFileSync(SRC, 'utf8');
// Strip the leading banner comment ─ identical shape to what split-css.js
// emitted in the previous pass.  We re-index everything against the
// post-banner content.
const stripped = raw.replace(/^\/\*[\s\S]*?\*\/\s*/, '');
const lines = stripped.split('\n');

// Section line ranges (1-indexed, inclusive) against the BANNER-STRIPPED
// content.  Verified by `grep ^/\\*` against the old style.css; see the
// section markers in the comments at the top of each range.
const SECTIONS = [
  { file: 'style.css',          banner: 'base — globals, root vars, body, scrollbar',
    ranges: [[1,    89]] },        // reset, scrollbar, :root, body, before App Layout
  { file: 'style.sidemenu.css', banner: 'side-menu / sidebar',
    ranges: [[90,   397]] },       // App Layout + side-menu through highlighted-tag sub-menu
  { file: 'style.search.css',   banner: 'search panel & filters (incl. trailing overrides)',
    ranges: [[398, 892], [1702, 1804]] }, // sources controls + filters; second range is the trailing search-grid overrides
  { file: 'style.buttons.css',  banner: 'buttons, refresh animations, tablet/desktop visibility',
    ranges: [[893,  1085]] },
  { file: 'style.modal.css',    banner: 'note-editor modal, form fields, score dice, footer',
    ranges: [[1086, 1701]] },
  { file: 'style.cards.css',    banner: 'note cards (grid + content / Quill text)',
    ranges: [[1805, 1971], [2528, 2993]] }, // grid + card content; selection lives between them in the original file but is its own bundle and is verified non-overlapping
  { file: 'style.selection.css',banner: 'manual selection mode, bulk ops, select-action-bar',
    ranges: [[1972, 2527]] },
  { file: 'style.attachments.css', banner: 'image upload, attachment viewers, multi-attachment strip',
    ranges: [[2994, 3698]] },
  { file: 'style.entities.css', banner: 'author / source / tag cards, rename, tag-operations panel, notifications',
    ranges: [[3699, 4556]] },
  { file: 'style.settings.css', banner: 'settings page, type management, translations',
    ranges: [[4557, 5086]] },
  { file: 'style.dialogs.css',  banner: 'merge modal & custom confirm dialog',
    ranges: [[5087, 5378]] },
  { file: 'style.views.css',    banner: 'gallery & list-pane views, training calendar, encryption UI, banners',
    ranges: [[5379, lines.length]] },
];

// Adjust the SECTIONS table below if the banner line count differs from the
// reference run.  We compute it by locating the first occurrence of "/* App
// Layout with Side Menu */" — section #2's start anchor.
const APP_LAYOUT = lines.findIndex(l => /^\/\* App Layout with Side Menu \*\/$/.test(l));
if (APP_LAYOUT < 0) {
  throw new Error('Could not locate "App Layout with Side Menu" anchor.  Aborting.');
}
// expected: section #2 begins exactly at APP_LAYOUT+1 (1-indexed: APP_LAYOUT+1+1 if 0-indexed math)
const expectedSidemenuStart = SECTIONS[1].ranges[0][0];
const actualSidemenuStart = APP_LAYOUT + 1; // 1-indexed line number
if (expectedSidemenuStart !== actualSidemenuStart) {
  console.error(`Anchor mismatch: expected sidemenu start at line ${expectedSidemenuStart}, got ${actualSidemenuStart}.`);
  console.error('Update the SECTIONS table at the top of this script and re-run.');
  process.exit(1);
}

function makeBanner(label) {
  return `/* ============================================================
   Misa Notes — ${label}
   Generated by scripts/split-base-css.js.  Load order in index.html:
       style.css → sidemenu → search → buttons → modal → cards →
       selection → attachments → entities → settings → dialogs → views
       → style.mobile.css → style.small.css → style.medium.css
   ============================================================ */\n\n`;
}

// Build per-file output and write.
const totals = { lines: 0, bytes: 0 };
const summary = [];
for (const s of SECTIONS) {
  const chunks = [];
  for (const [a, b] of s.ranges) {
    // slice is 0-indexed and end-exclusive; lines[a-1..b]
    chunks.push(lines.slice(a - 1, b).join('\n'));
  }
  const body = chunks.join('\n\n');
  const out  = makeBanner(s.banner) + body + (body.endsWith('\n') ? '' : '\n');
  const dest = path.join(ROOT, 'public', s.file);
  fs.writeFileSync(dest, out);
  const stat = fs.statSync(dest);
  const lc   = out.split('\n').length;
  summary.push({ file: s.file, lines: lc, bytes: stat.size });
  totals.lines += lc;
  totals.bytes += stat.size;
}

console.log('Wrote feature CSS files:');
const colW = Math.max(...summary.map(r => r.file.length));
for (const r of summary) {
  console.log(`  public/${r.file.padEnd(colW)}   ${String(r.lines).padStart(5)} lines   ${String(r.bytes).padStart(8)} bytes`);
}
console.log(`  ${' '.repeat(colW + 8)}   ${String(totals.lines).padStart(5)} lines   ${String(totals.bytes).padStart(8)} bytes total`);
